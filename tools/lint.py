"""Static checks for the datapack that Minecraft itself won't catch.

Rules (each one protects an invariant from the design docs):
  json        every .json / .mcmeta file parses
  namespace   datapack files live under data/euchre/, except the two
              minecraft:load / minecraft:tick function tags
  prefix      scoreboard objectives, entity tags and storages are euchre-prefixed
  diamonds    only escrow/collect may remove diamonds and only escrow/deliver may
              give them (the escrow choke points; see docs/escrow.md)
  cushions    cushions are player-owned: nothing may kill them
  overflow    entity positions are never scaled by more than 10 into a score
  nbt-path    no `list[0]{filter}` paths (invalid in Minecraft)
  syntax      quotes and brackets balance on every command line
  dispatch    phase dispatch tables return after the first matching handler
  refs        every `function euchre:...` reference resolves to a file
  rp-refs     resource pack item models -> models -> textures all resolve

Usage: python tools/lint.py   (exit 1 on any violation)
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DP_DATA = ROOT / "datapack" / "data"
FUNC_ROOTS = {
    "euchre": DP_DATA / "euchre" / "function",
    "euchre_test": ROOT / "tests" / "packtest" / "data" / "euchre_test" / "function",
}
ALLOWED_MINECRAFT = {
    DP_DATA / "minecraft" / "tags" / "function" / "load.json",
    DP_DATA / "minecraft" / "tags" / "function" / "tick.json",
}
# The only functions allowed to touch diamonds, relative to data/euchre/function/.
# Both are generated by tools/gen.py from PLAIN_DIAMOND.
DIAMOND_TAKE = "gen/escrow_collect.mcfunction"
DIAMOND_GIVE = "gen/escrow_give.mcfunction"

RE_DIAMOND = re.compile(r"(?<![\w.])(?:minecraft:)?diamond(?![\w])")
RE_OBJECTIVE = re.compile(r"\bscoreboard objectives add (\S+)")
RE_TAG = re.compile(r"\btag \S+ (?:add|remove) (\S+)")
RE_STORAGE = re.compile(r"\bstorage ([a-z0-9_.-]+):")
RE_FUNC_REF = re.compile(r"\bfunction (euchre(?:_test)?):([a-z0-9_/.-]+)")
RE_KILL_CUSHION = re.compile(r"\bkill\b.*cushion")
# `data get ... Pos[i] <scale>` into a 32-bit score: coordinates reach +-30,000,000,
# so any scale above 10 can overflow (x100 breaks past ~21.4M blocks).
# An NBT path can't follow a list index with a compound filter (`list[0]{a:1}`);
# Minecraft rejects the whole function at load time. Copy the element out first.
RE_INDEX_FILTER = re.compile(r"\[-?\d+\]\{")
RE_POS_SCALE = re.compile(r"\bPos\[\d\]\s+(\d+(?:\.\d+)?)")

errors: list[str] = []


def err(path: Path, line: int | None, rule: str, msg: str) -> None:
    where = path.relative_to(ROOT).as_posix() + (f":{line}" if line else "")
    errors.append(f"{where}: [{rule}] {msg}")


def check_json() -> None:
    for p in ROOT.rglob("*"):
        if p.suffix in {".json", ".mcmeta"} and ".git" not in p.parts and "dist" not in p.parts:
            try:
                json.loads(p.read_text(encoding="utf-8"))
            except json.JSONDecodeError as e:
                err(p, e.lineno, "json", e.msg)


def check_namespace() -> None:
    for p in DP_DATA.rglob("*"):
        if p.is_file() and p.parts[len(DP_DATA.parts)] != "euchre" and p not in ALLOWED_MINECRAFT:
            err(p, None, "namespace", "only data/euchre/ (plus minecraft load/tick tags) is allowed")


def function_exists(ns: str, name: str) -> bool:
    root = FUNC_ROOTS.get(ns)
    return root is not None and (root / f"{name}.mcfunction").is_file()


def balance_problem(line: str) -> str | None:
    """Every command is one line, so its quotes and brackets must balance on that
    line. Catches a string accidentally split across lines (which Minecraft reports
    only at load time, by refusing the whole function)."""
    stack: list[str] = []
    pairs = {"}": "{", "]": "[", ")": "("}
    quote: str | None = None
    escaped = False
    for ch in line:
        if quote:
            if escaped:
                escaped = False
            elif ch == "\\":
                escaped = True
            elif ch == quote:
                quote = None
        elif ch in "\"'":
            quote = ch
        elif ch in "{[(":
            stack.append(ch)
        elif ch in pairs:
            if not stack or stack.pop() != pairs[ch]:
                return f"unbalanced '{ch}'"
    if quote:
        return "unterminated string"
    if stack:
        return f"unclosed '{stack[-1]}'"
    return None


RE_PHASE_DISPATCH = re.compile(r"^execute if score @s euchre\.phase matches \S+ run function ")


def check_phase_dispatch(p: Path, lines: list[str]) -> None:
    """Several `if phase matches X run function` lines in a row form a dispatch
    table. Unless each one returns, a handler that changes the phase makes a
    later line fire in the same tick (this once skipped the game-over pause).
    Files whose handlers never change the phase can opt out with a comment
    containing `lint: phase-chain-ok`."""
    if any("lint: phase-chain-ok" in l for l in lines):
        return
    hits = [n for n, l in enumerate(lines, 1) if RE_PHASE_DISPATCH.match(l.strip())]
    if len(hits) >= 2:
        for n in hits:
            err(p, n, "dispatch", "phase dispatch must use `run return run function` (or mark the file phase-chain-ok)")


def check_mcfunctions() -> None:
    files = list((DP_DATA / "euchre").rglob("*.mcfunction"))
    files += list((ROOT / "tests" / "packtest").rglob("*.mcfunction"))
    euchre_fn = DP_DATA / "euchre" / "function"
    for p in files:
        in_pack = euchre_fn in p.parents
        relname = p.relative_to(euchre_fn).as_posix() if in_pack else None
        all_lines = p.read_text(encoding="utf-8").splitlines()
        if in_pack:
            check_phase_dispatch(p, all_lines)
        for n, raw in enumerate(all_lines, 1):
            line = raw.strip()
            if not line or line.startswith("#"):
                continue
            body = line[1:] if line.startswith("$") else line  # macro lines

            problem = balance_problem(body)
            if problem:
                err(p, n, "syntax", problem)

            for name in RE_OBJECTIVE.findall(body):
                if not name.startswith("euchre."):
                    err(p, n, "prefix", f"objective '{name}' must start with 'euchre.'")
            for name in RE_TAG.findall(body):
                if not name.startswith(("euchre.", "euchre_test.", "$(")):
                    err(p, n, "prefix", f"entity tag '{name}' must start with 'euchre.'")
            for ns in RE_STORAGE.findall(body):
                if ns not in ("euchre", "euchre_test"):
                    err(p, n, "prefix", f"storage namespace '{ns}' must be euchre")

            if RE_INDEX_FILTER.search(body):
                err(p, n, "nbt-path", "a list index can't be followed by a {filter} in an NBT path")

            for scale in RE_POS_SCALE.findall(body):
                if float(scale) > 10:
                    err(p, n, "overflow", f"Pos scale {scale} can overflow a score far from spawn; use 10 or less")

            if in_pack and RE_DIAMOND.search(body):
                # Diamonds may be mentioned only in the two choke points, and
                # within them only cleared in one and only given in the other.
                allowed = (
                    relname == DIAMOND_TAKE and not re.search(r"\bgive\b", body)
                ) or (relname == DIAMOND_GIVE and not re.search(r"\bclear\b", body))
                if not allowed:
                    err(p, n, "diamonds",
                        f"diamonds may only be cleared in {DIAMOND_TAKE} and given in {DIAMOND_GIVE}")

            # Tests may clean up the cushions their own fixtures summoned.
            if in_pack and RE_KILL_CUSHION.search(body):
                err(p, n, "cushions", "cushions belong to the builder and must never be killed")

            for ns, name in RE_FUNC_REF.findall(body):
                if "$(" not in name and not function_exists(ns, name):
                    err(p, n, "refs", f"function {ns}:{name} does not exist")


def check_json_refs() -> None:
    """Function references inside JSON (function tags, advancement rewards)."""
    refs: list[tuple[Path, str]] = []
    for p in DP_DATA.glob("*/tags/function/*.json"):
        refs += [(p, v) for v in json.loads(p.read_text(encoding="utf-8")).get("values", [])]
    for p in DP_DATA.glob("*/advancement/**/*.json"):
        fn = json.loads(p.read_text(encoding="utf-8")).get("rewards", {}).get("function")
        if fn:
            refs.append((p, fn))
    for p, ref in refs:
        ns, _, name = ref.partition(":")
        if ns.startswith("euchre") and not function_exists(ns, name):
            err(p, None, "refs", f"function {ref} does not exist")


def check_resource_pack() -> None:
    """Every item definition's models exist, and every model's textures exist.
    (A broken reference only shows up in game as a purple-and-black square.)
    Also: every card the datapack can create has both of its item models."""
    rp = ROOT / "resourcepack" / "assets"

    def asset(ref: str, kind: str, ext: str) -> Path:
        ns, _, path = ref.partition(":")
        return rp / ns / kind / f"{path}{ext}"

    def walk(node, found: list[str]) -> None:
        if isinstance(node, dict):
            if node.get("type") == "minecraft:model" and "model" in node:
                found.append(node["model"])
            for v in node.values():
                walk(v, found)
        elif isinstance(node, list):
            for v in node:
                walk(v, found)

    for p in (rp / "euchre" / "items").glob("*.json"):
        refs: list[str] = []
        walk(json.loads(p.read_text(encoding="utf-8")), refs)
        for ref in refs:
            if not asset(ref, "models", ".json").is_file():
                err(p, None, "rp-refs", f"model {ref} does not exist")
    for p in (rp / "euchre" / "models").rglob("*.json"):
        for ref in json.loads(p.read_text(encoding="utf-8")).get("textures", {}).values():
            if ref.startswith("euchre:") and not asset(ref, "textures", ".png").is_file():
                err(p, None, "rp-refs", f"texture {ref} does not exist")
    for cid in range(24):
        for name in (f"card_{cid}", f"card_face_{cid}"):
            if not (rp / "euchre" / "items" / f"{name}.json").is_file():
                err(rp / "euchre" / "items", None, "rp-refs", f"item model euchre:{name} is missing")


def main() -> int:
    check_json()
    check_namespace()
    check_mcfunctions()
    check_json_refs()
    check_resource_pack()
    for e in errors:
        print(e, file=sys.stderr)
    if errors:
        print(f"lint: {len(errors)} problem(s)", file=sys.stderr)
        return 1
    print("lint: ok")
    return 0


if __name__ == "__main__":
    sys.exit(main())
