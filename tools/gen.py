def gen_card_table() -> dict[Path, str]:
    """Card lookup table in storage, indexed by card id (0-23)."""
    entries = []
    for cid in range(DECK_SIZE):
        c = card(cid)
        entries.append(
            f'{{id:{c["id"]},suit:{c["suit"]},rank:{c["rank"]},'
            f'name:"{c["name"]}",color:"{c["color"]}",key:"{c["key"]}"}}'
        )
    body = (
        HEADER
        + "# Card lookup table: euchre:cards table[<id>]. id = suit*6 + rank.\n"
        + "# suit 0=clubs 1=spades 2=diamonds 3=hearts; rank 0=9 1=10 2=J 3=Q 4=K 5=A.\n"
        + "data modify storage euchre:cards table set value ["
        + ",".join(entries)
        + "]\n"
    )
    return {DP / "function" / "gen" / "card_table.mcfunction": body}


def gen_hotbar_helpers() -> dict[Path, str]:
    """Per-slot helpers. Commands can't loop over slot names, so we unroll."""
    find = [
        HEADER,
        "# Returns the index of the first empty hotbar slot of @s, or -1 if none.\n",
        "# Usage: execute store result score #slot euchre.tmp run function euchre:gen/first_empty_hotbar_slot\n",
    ]
    for i in range(HOTBAR_SLOTS):
        find.append(f"execute unless items entity @s hotbar.{i} * run return {i}\n")
    find.append("return -1\n")

    count = [
        HEADER,
        "# Returns how many hotbar slots of @s are empty (0-9).\n",
        "scoreboard players set #empty euchre.tmp 0\n",
    ]
    for i in range(HOTBAR_SLOTS):
        count.append(
            f"execute unless items entity @s hotbar.{i} * run scoreboard players add #empty euchre.tmp 1\n"
        )
    count.append("return run scoreboard players get #empty euchre.tmp\n")

    gen = DP / "function" / "gen"
    return {
        gen / "first_empty_hotbar_slot.mcfunction": "".join(find),
        gen / "count_empty_hotbar_slots.mcfunction": "".join(count),
    }


def gen_objectives() -> dict[Path, str]:
    add = [HEADER, "# Create every objective. Harmless if they already exist (the command just fails).\n"]
    rem = [HEADER, "# Remove every objective (used by euchre:uninstall).\n"]
    for name, criterion in OBJECTIVES:
        add.append(f"scoreboard objectives add {name} {criterion}\n")
        rem.append(f"scoreboard objectives remove {name}\n")
    gen = DP / "function" / "gen"
    return {
        gen / "objectives_add.mcfunction": "".join(add),
        gen / "objectives_remove.mcfunction": "".join(rem),
    }


def gen_card_helpers() -> dict[Path, str]:
    """Everything that creates, counts or removes card items, so the item's
    definition (CARD_ITEM / CARD_PREDICATE) appears in exactly one place."""
    gen = DP / "function" / "gen"
    files = {
        "give_card": (
            "# As a player: put a card into hotbar slot $(slot).\n"
            "# Args: slot, id, name, color, tid, nonce.\n"
            f"$item replace entity @s hotbar.$(slot) with {CARD_ITEM}\n"
        ),
        "card_to_contents": (
            "# As an item_display: show a card. Args: id, name, color, tid, nonce.\n"
            f"$item replace entity @s contents with {CARD_ITEM}\n"
        ),
        "count_cards": (
            "# As a player: returns how many card items (of any deal) they carry.\n"
            f"return run clear @s {CARD_PREDICATE} 0\n"
        ),
        "count_card": (
            "# As a player: returns how many copies of card $(id) from deal $(nonce) they carry.\n"
            f"$return run clear @s {CARD_BASE_ITEM}[custom_data~{{euchre:{{card:$(id),nonce:$(nonce)}}}}] 0\n"
        ),
        "clear_card": (
            "# As a player: remove card $(id) of deal $(nonce) (the one they just played).\n"
            f"$clear @s {CARD_BASE_ITEM}[custom_data~{{euchre:{{card:$(id),nonce:$(nonce)}}}}]\n"
        ),
        "clear_cards": (
            "# As a player: remove every card item. Cards belong to the table, never to\n"
            "# the player, so this never touches anything of value.\n"
            f"clear @s {CARD_PREDICATE}\n"
        ),
        "sweep_cards": (
            "# Card items may only exist in seated players' inventories. Remove any held by\n"
            "# someone else and any lying on the ground (dropped, thrown, or left over).\n"
            f"clear @a[tag=!euchre.seated] {CARD_PREDICATE}\n"
            f"execute as @e[type=minecraft:item] if items entity @s contents {CARD_PREDICATE} run kill @s\n"
        ),
    }
    return {gen / f"{name}.mcfunction": HEADER + body for name, body in files.items()}


def gen_deal_split() -> dict[Path, str]:
    """Split euchre:tmp shuffled (24 card ids) into hands and kitty. Fixed indices
    make rigged decks in tests predictable: seat s gets shuffled[5s..5s+4] and the
    kitty is shuffled[20..23], whose first card is turned up."""
    lines = [
        HEADER,
        "# Seat s gets shuffled[5s..5s+4]; the kitty is shuffled[20..23] (kitty[0] is the up card).\n",
        "data modify storage euchre:tmp game set value {hands:[[],[],[],[]],kitty:[]}\n",
    ]
    for i in range(DECK_SIZE):
        target = f"hands[{i // 5}]" if i < 20 else "kitty"
        lines.append(f"data modify storage euchre:tmp game.{target} append from storage euchre:tmp shuffled[{i}]\n")
    return {DP / "function" / "gen" / "deal_split.mcfunction": "".join(lines)}


def gen_bid_prompts() -> dict[Path, str]:
    """Clickable chat prompts for bidding. Each button runs /trigger euchre.act
    with a code: 1 pass, 2 order up, 3 order up alone, 10+suit name a suit,
    20+suit name a suit alone (see bid/act)."""
    prefix = '{text:"[Euchre] ",color:"gold"}'

    def button(label: str, color: str, code: int, hover: str) -> str:
        return (f'{{text:"[{label}]",color:"{color}",bold:true,'
                f'click_event:{{action:"run_command",command:"/trigger euchre.act set {code}"}},'
                f'hover_event:{{action:"show_text",value:"{hover}"}}}}')

    def suit_color(s: int) -> str:
        return "red" if SUITS[s]["color"] == "red" else "white"

    pass_btn = button("Pass", "gray", 1, "Let the next player decide.")

    r1 = [HEADER, "# As the first-round bidder. #up_suit: suit of the up card.\n"]
    for s in range(4):
        sym = SUITS[s]["symbol"]
        order = button(f"Order up {sym}", suit_color(s), 2,
                       f"Make {sym} trump. The dealer picks up the up card and discards one.")
        alone = button(f"Order up {sym} alone", suit_color(s), 3,
                       f"Make {sym} trump and play without your partner: 4 points for all five tricks.")
        r1.append(f'execute if score #up_suit euchre.tmp matches {s} run tellraw @s [{prefix},'
                  f'{{text:"Your bid: ",color:"aqua"}},{order},{{text:" "}},{alone},{{text:" "}},{pass_btn}]\n')

    r2 = [HEADER, "# As the second-round bidder. #down: the turned-down suit, which can't be named.\n",
          "# #canpass: 0 when the dealer is stuck (stick the dealer), else 1.\n"]
    for down in range(4):
        for canpass in (0, 1):
            parts = []
            for s in range(4):
                if s == down:
                    continue
                sym = SUITS[s]["symbol"]
                parts.append(button(f"{sym}", suit_color(s), 10 + s, f"Name {sym} trump."))
            if canpass:
                parts.append(pass_btn)
            joined = ',{text:" "},'.join(parts)
            alone_parts = [button(f"{SUITS[s]['symbol']}", suit_color(s), 20 + s,
                                  f"Name {SUITS[s]['symbol']} trump and play without your partner.")
                           for s in range(4) if s != down]
            alone_joined = ',{text:" "},'.join(alone_parts)
            label = "Name trump: " if canpass else "Stick the dealer! Name trump: "
            r2.append(f'execute if score #down euchre.tmp matches {down} if score #canpass euchre.tmp matches {canpass} '
                      f'run tellraw @s [{prefix},{{text:"{label}",color:"aqua"}},{joined},'
                      f'{{text:"  or alone: ",color:"gray"}},{alone_joined}]\n')

    gen = DP / "function" / "gen"
    return {gen / "bid_prompt1.mcfunction": "".join(r1), gen / "bid_prompt2.mcfunction": "".join(r2)}


# --------------------------------------------------------------------------- #
# Reference rules model. The datapack's rules/* functions implement these with
# scoreboard arithmetic; the golden tests below check them against this model.
# --------------------------------------------------------------------------- #

JACK = 2  # rank index of the jack


def ref_eff_suit(cid: int, trump: int) -> int:
    """Effective suit: the left bower (jack of trump's colour) counts as trump."""
    suit, rank = divmod(cid, len(RANKS))
    return trump if rank == JACK and suit == trump ^ 1 else suit


def ref_power(cid: int, trump: int, led: int) -> int:
    """Trick-taking strength: right bower 20, left 19, other trump 12+rank,
    a card of the led suit rank+1, anything else 0."""
    suit, rank = divmod(cid, len(RANKS))
    eff = ref_eff_suit(cid, trump)
    if eff == trump:
        if rank == JACK:
            return 20 if suit == trump else 19
        return 12 + rank
    if eff == led:
        return rank + 1
    return 0


def ref_is_legal(cid: int, hand: list[int], trump: int, led: int | None) -> bool:
    """Follow suit (by effective suit) if you can; anything goes when leading."""
    if led is None or ref_eff_suit(cid, trump) == led:
        return True
    return not any(ref_eff_suit(c, trump) == led for c in hand)


def ref_score_hand(maker_team: int, maker_tricks: int, alone: bool) -> tuple[int, int]:
    """(team that scores, points): makers 3-4 tricks 1, all 5 tricks 2 (4 alone);
    makers euchred (under 3 tricks) give the defenders 2."""
    if maker_tricks < 3:
        return 1 - maker_team, 2
    if maker_tricks == 5:
        return maker_team, 4 if alone else 2
    return maker_team, 1


def ref_trick_winner(trick: list[tuple[int, int]], trump: int) -> int:
    """trick: [(seat, card), ...] in play order. Returns the winning seat."""
    led = ref_eff_suit(trick[0][1], trump)
    return max(trick, key=lambda sc: ref_power(sc[1], trump, led))[0]


def gen_golden_tests() -> dict[Path, str]:
    import random

    gh = "# GENERATED by tools/gen.py from its reference rules model — DO NOT EDIT.\n"
    out: dict[Path, str] = {}

    lines = [gh, "# Effective suit of every card under every trump (left bower = trump).\n"]
    for trump in range(4):
        lines.append(f"scoreboard players set #trump euchre.tmp {trump}\n")
        for cid in range(DECK_SIZE):
            lines.append(f"scoreboard players set #card euchre.tmp {cid}\n")
            lines.append("function euchre:rules/eff_suit\n")
            lines.append(f"assert score #eff euchre.tmp matches {ref_eff_suit(cid, trump)}\n")
    out[GOLDEN / "eff_suit.mcfunction"] = "".join(lines)

    for trump in range(4):
        lines = [gh, f"# Power of every card with trump {SUITS[trump]['key']}, for every led suit.\n",
                 f"scoreboard players set #trump euchre.tmp {trump}\n"]
        for led in range(4):
            lines.append(f"scoreboard players set #led euchre.tmp {led}\n")
            for cid in range(DECK_SIZE):
                lines.append(f"scoreboard players set #card euchre.tmp {cid}\n")
                lines.append("function euchre:rules/power\n")
                lines.append(f"assert score #power euchre.tmp matches {ref_power(cid, trump, led)}\n")
        out[GOLDEN / f"power_{SUITS[trump]['key']}.mcfunction"] = "".join(lines)

    # Seeded random tricks (fixed seed: the file must be reproducible).
    rng = random.Random(1234)
    lines = [gh, "# Winners of 60 random tricks (some with 3 cards, as when a player goes alone).\n"]
    for _ in range(60):
        trump = rng.randrange(4)
        size = rng.choice([4, 4, 4, 3])
        first = rng.randrange(4)
        seats = [(first + i) % 4 for i in range(size)]
        cards = rng.sample(range(DECK_SIZE), size)
        trick = list(zip(seats, cards))
        snbt = ",".join(f"{{seat:{s},card:{c}}}" for s, c in trick)
        lines.append(f"scoreboard players set #trump euchre.tmp {trump}\n")
        lines.append(f"data modify storage euchre:tmp game.trick set value [{snbt}]\n")
        lines.append("function euchre:rules/trick_winner\n")
        lines.append(f"assert score #winner euchre.tmp matches {ref_trick_winner(trick, trump)}\n")
    out[GOLDEN / "trick_winner.mcfunction"] = "".join(lines)

    # Seeded random follow-suit decisions. Hands are biased towards jacks so the
    # left-bower cases come up often.
    rng = random.Random(5678)
    lines = [gh, "# 150 random follow-suit decisions (is this card legal from this hand?).\n"]
    jacks = [s * len(RANKS) + JACK for s in range(4)]
    legal_count = 0
    for _ in range(150):
        trump = rng.randrange(4)
        size = rng.randint(1, 5)
        pool = list(range(DECK_SIZE))
        hand = rng.sample(pool, size)
        if rng.random() < 0.5:
            j = rng.choice(jacks)
            if j not in hand:
                hand[0] = j
        cid = rng.choice(hand)
        led_card = rng.choice([c for c in range(DECK_SIZE) if c not in hand])
        led = None if rng.random() < 0.1 else ref_eff_suit(led_card, trump)
        legal = ref_is_legal(cid, hand, trump, led)
        legal_count += legal
        lines.append(f"scoreboard players set #trump euchre.tmp {trump}\n")
        lines.append(f"scoreboard players set #led euchre.tmp {-1 if led is None else led}\n")
        lines.append(f"data modify storage euchre:tmp gh set value [{','.join(map(str, hand))}]\n")
        lines.append(f"scoreboard players set #card euchre.tmp {cid}\n")
        lines.append("execute store success score #ok euchre.tmp run function euchre:rules/is_legal\n")
        lines.append(f"assert score #ok euchre.tmp matches {int(legal)}\n")
        lines.append(f"assert score #card euchre.tmp matches {cid}\n")
    # Guard against a degenerate sample (all legal or all illegal) slipping in.
    assert 30 < legal_count < 140, legal_count
    out[GOLDEN / "is_legal.mcfunction"] = "".join(lines)

    lines = [gh, "# Hand scoring for every maker team, trick count and lone/partnered hand.\n"]
    for team in (0, 1):
        for tricks in range(6):
            for alone in (False, True):
                pteam, pts = ref_score_hand(team, tricks, alone)
                lines.append(f"scoreboard players set #mteam euchre.tmp {team}\n")
                lines.append(f"scoreboard players set #mtricks euchre.tmp {tricks}\n")
                lines.append(f"scoreboard players set #alone euchre.tmp {int(alone)}\n")
                lines.append("function euchre:rules/score_hand\n")
                lines.append(f"assert score #pteam euchre.tmp matches {pteam}\n")
                lines.append(f"assert score #pts euchre.tmp matches {pts}\n")
    out[GOLDEN / "score_hand.mcfunction"] = "".join(lines)
    return out


def gen_escrow() -> dict[Path, str]:
    """The only two functions in the pack that touch diamonds (tools/lint.py
    enforces this). Both are generated so PLAIN_DIAMOND is written exactly once."""
    gen = DP / "function" / "gen"
    collect = HEADER + f"""# As a player. The ONLY function that removes diamonds from anyone.
#   #take euchre.tmp = 0: returns how many plain diamonds they carry (removes none)
#   #take euchre.tmp = 1: removes up to $(amount) plain diamonds, returns how many
# Only "plain" diamonds count (see PLAIN_DIAMOND in tools/gen.py): renamed or
# otherwise modified diamonds are never counted or taken.
execute if score #take euchre.tmp matches 0 run return run clear @s {PLAIN_DIAMOND} 0
$return run clear @s {PLAIN_DIAMOND} $(amount)
"""
    give = HEADER + """# As a player tagged euchre.payee. The ONLY function that gives diamonds to anyone.
# Gives $(amount) plain diamonds. Whatever doesn't fit is dropped at the player's
# feet as an item only they can pick up (vanilla /give); mark those drops so
# they never despawn.
$give @s minecraft:diamond $(amount)
execute as @e[type=minecraft:item,distance=..3] if items entity @s contents minecraft:diamond run function euchre:escrow/protect_drop
"""
    return {gen / "escrow_collect.mcfunction": collect, gen / "escrow_give.mcfunction": give}


GENERATORS = [gen_card_table, gen_hotbar_helpers, gen_objectives, gen_card_helpers, gen_deal_split,
              gen_bid_prompts, gen_escrow, gen_golden_tests]


# --------------------------------------------------------------------------- #


def build_all() -> dict[Path, str]:
    out: dict[Path, str] = {}
    for g in GENERATORS:
        for path, content in g().items():
            if path in out:
                raise RuntimeError(f"two generators produced {path}")
            out[path] = content
    return out


def rel(p: Path) -> str:
    return p.relative_to(ROOT).as_posix()


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="verify instead of writing")
    args = ap.parse_args()

    files = build_all()
    existing = {p for root in GENERATED_ROOTS if root.exists() for p in root.rglob("*") if p.is_file()}
    orphans = sorted(existing - set(files))

    if args.check:
        problems = [f"orphan: {rel(p)}" for p in orphans]
        for path, content in sorted(files.items()):
            if not path.exists():
                problems.append(f"missing: {rel(path)}")
            elif path.read_text(encoding="utf-8") != content:
                problems.append(f"stale: {rel(path)}")
        for p in problems:
            print(p, file=sys.stderr)
        if problems:
            print("Generated files are out of date. Run: python tools/gen.py", file=sys.stderr)
            return 1
        print(f"gen: {len(files)} generated files up to date")
        return 0

    for p in orphans:
        p.unlink()
        print(f"removed orphan {rel(p)}")
    for path, content in sorted(files.items()):
        path.parent.mkdir(parents=True, exist_ok=True)
        if not path.exists() or path.read_text(encoding="utf-8") != content:
            path.write_text(content, encoding="utf-8", newline="\n")
            print(f"wrote {rel(path)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
