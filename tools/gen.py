"""Generate the repetitive parts of the datapack and resource pack.

Everything this script writes lives under a `gen/` directory (or is otherwise
listed in GENERATED_ROOTS) and starts with a DO-NOT-EDIT header. Generated files
are committed so the repo stays a drop-in pack straight from git; CI runs
`python tools/gen.py --check` to make sure nobody edited them by hand or forgot
to regenerate.

Standard library only, so contributors need nothing but Python 3.10+.

Usage:
    python tools/gen.py           # (re)write generated files
    python tools/gen.py --check   # exit 1 if any generated file is stale/orphaned
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DP = ROOT / "datapack" / "data" / "euchre"
RP = ROOT / "resourcepack" / "assets" / "euchre"

# Directories owned entirely by this script. Any file in them that the
# generators did not produce is reported as an orphan by --check.
GENERATED_ROOTS = [
    DP / "function" / "gen",
]

HEADER = "# GENERATED by tools/gen.py — DO NOT EDIT. Change the generator and re-run it.\n"

# --------------------------------------------------------------------------- #
# Shared constants. tools/lint.py imports these too, so each fact lives here once.
# --------------------------------------------------------------------------- #

SUITS = [  # index == suit id. Same-colour suit is `suit XOR 1`.
    {"key": "clubs", "symbol": "♣", "color": "gray"},
    {"key": "spades", "symbol": "♠", "color": "gray"},
    {"key": "diamonds", "symbol": "♦", "color": "red"},
    {"key": "hearts", "symbol": "♥", "color": "red"},
]
RANKS = ["9", "10", "J", "Q", "K", "A"]  # index == rank id
RANK_KEYS = ["nine", "ten", "jack", "queen", "king", "ace"]
DECK_SIZE = len(SUITS) * len(RANKS)  # 24
HOTBAR_SLOTS = 9

# Item used as the base for card items. Must be inert in survival (not placeable,
# no use action, not a crafting/fuel/brewing ingredient) so that reissuing a
# card can never create value. To be confirmed by the M0 spike, see
# docs/verification.md.
CARD_BASE_ITEM = "minecraft:debug_stick"

# Item predicate for a "plain" diamond, so renamed, tagged, or otherwise modified
# diamonds are never counted or taken. Only escrow/collect may use it, and
# tools/lint.py enforces that.
#
# Every item carries *default* components (item_name, item_model, lore,
# enchantments, ...), so `!lore` or `!enchantments` would reject plain diamonds
# too. Components a plain diamond has by default are matched against their
# default values instead; components it lacks by default are tested with `!`.
# Verified in-game on 26.3 (docs/verification.md, item n).
PLAIN_DIAMOND = (
    "minecraft:diamond[!custom_data,!custom_name,!enchantment_glint_override,"
    "lore=[],enchantments={}]"
)


# Every scoreboard objective the pack owns, with its criterion. load adds them and
# uninstall removes them; both lists are generated from here so they can't drift.
OBJECTIVES = [
    # Global registers (fake players such as #active) and scratch space
    ("euchre.g", "dummy"),
    ("euchre.tmp", "dummy"),
    # Per player
    ("euchre.pid", "dummy"),
    ("euchre.tid", "dummy"),
    ("euchre.seat", "dummy"),
    ("euchre.act", "trigger"),
    ("euchre.left", "minecraft.custom:minecraft.leave_game"),
    # Per table, stored on the table's marker entity
    ("euchre.seated", "dummy"),
    ("euchre.phase", "dummy"),
    ("euchre.resume", "dummy"),
    ("euchre.dealer", "dummy"),
    ("euchre.turn", "dummy"),
    ("euchre.leader", "dummy"),
    ("euchre.trump", "dummy"),
    ("euchre.upcard", "dummy"),
    ("euchre.maker", "dummy"),
    ("euchre.alone", "dummy"),
    ("euchre.trickno", "dummy"),
    ("euchre.tricks0", "dummy"),
    ("euchre.tricks1", "dummy"),
    ("euchre.pts0", "dummy"),
    ("euchre.pts1", "dummy"),
    ("euchre.timer", "dummy"),
    ("euchre.nonce", "dummy"),
]


def card(cid: int) -> dict:
    suit, rank = divmod(cid, len(RANKS))
    s = SUITS[suit]
    return {
        "id": cid,
        "suit": suit,
        "rank": rank,
        "name": f"{RANKS[rank]}{s['symbol']}",
        "color": s["color"],
        "key": f"{RANK_KEYS[rank]}_of_{s['key']}",
    }


# --------------------------------------------------------------------------- #
# Generators: each returns {path: content}.
# --------------------------------------------------------------------------- #


def gen_card_table() -> dict[Path, str]:
    """Card lookup table in storage, indexed by card id (0-23)."""
    entries = []
    for cid in range(DECK_SIZE):
        c = card(cid)
        entries.append(
            f'{{id:{c["id"]},suit:{c["suit"]},rank:{c["rank"]},'
            f'name:"{c["name"]}",color:"{c["color"]}",key:"{c["key"]}"}}'
        )
    body = (
        HEADER
        + "# Card lookup table: euchre:cards table[<id>]. id = suit*6 + rank.\n"
        + "# suit 0=clubs 1=spades 2=diamonds 3=hearts; rank 0=9 1=10 2=J 3=Q 4=K 5=A.\n"
        + "data modify storage euchre:cards table set value ["
        + ",".join(entries)
        + "]\n"
    )
    return {DP / "function" / "gen" / "card_table.mcfunction": body}


def gen_hotbar_helpers() -> dict[Path, str]:
    """Per-slot helpers. Commands can't loop over slot names, so we unroll."""
    find = [
        HEADER,
        "# Returns the index of the first empty hotbar slot of @s, or -1 if none.\n",
        "# Usage: execute store result score #slot euchre.tmp run function euchre:gen/first_empty_hotbar_slot\n",
    ]
    for i in range(HOTBAR_SLOTS):
        find.append(f"execute unless items entity @s hotbar.{i} * run return {i}\n")
    find.append("return -1\n")

    count = [
        HEADER,
        "# Returns how many hotbar slots of @s are empty (0-9).\n",
        "scoreboard players set #empty euchre.tmp 0\n",
    ]
    for i in range(HOTBAR_SLOTS):
        count.append(
            f"execute unless items entity @s hotbar.{i} * run scoreboard players add #empty euchre.tmp 1\n"
        )
    count.append("return run scoreboard players get #empty euchre.tmp\n")

    gen = DP / "function" / "gen"
    return {
        gen / "first_empty_hotbar_slot.mcfunction": "".join(find),
        gen / "count_empty_hotbar_slots.mcfunction": "".join(count),
    }


def gen_objectives() -> dict[Path, str]:
    add = [HEADER, "# Create every objective. Harmless if they already exist (the command just fails).\n"]
    rem = [HEADER, "# Remove every objective (used by euchre:uninstall).\n"]
    for name, criterion in OBJECTIVES:
        add.append(f"scoreboard objectives add {name} {criterion}\n")
        rem.append(f"scoreboard objectives remove {name}\n")
    gen = DP / "function" / "gen"
    return {
        gen / "objectives_add.mcfunction": "".join(add),
        gen / "objectives_remove.mcfunction": "".join(rem),
    }


GENERATORS = [gen_card_table, gen_hotbar_helpers, gen_objectives]


# --------------------------------------------------------------------------- #


def build_all() -> dict[Path, str]:
    out: dict[Path, str] = {}
    for g in GENERATORS:
        for path, content in g().items():
            if path in out:
                raise RuntimeError(f"two generators produced {path}")
            out[path] = content
    return out


def rel(p: Path) -> str:
    return p.relative_to(ROOT).as_posix()


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="verify instead of writing")
    args = ap.parse_args()

    files = build_all()
    existing = {p for root in GENERATED_ROOTS if root.exists() for p in root.rglob("*") if p.is_file()}
    orphans = sorted(existing - set(files))

    if args.check:
        problems = [f"orphan: {rel(p)}" for p in orphans]
        for path, content in sorted(files.items()):
            if not path.exists():
                problems.append(f"missing: {rel(path)}")
            elif path.read_text(encoding="utf-8") != content:
                problems.append(f"stale: {rel(path)}")
        for p in problems:
            print(p, file=sys.stderr)
        if problems:
            print("Generated files are out of date. Run: python tools/gen.py", file=sys.stderr)
            return 1
        print(f"gen: {len(files)} generated files up to date")
        return 0

    for p in orphans:
        p.unlink()
        print(f"removed orphan {rel(p)}")
    for path, content in sorted(files.items()):
        path.parent.mkdir(parents=True, exist_ok=True)
        if not path.exists() or path.read_text(encoding="utf-8") != content:
            path.write_text(content, encoding="utf-8", newline="\n")
            print(f"wrote {rel(path)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
