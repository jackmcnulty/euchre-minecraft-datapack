    ("euchre.dealer", "dummy"),
    ("euchre.turn", "dummy"),
    ("euchre.leader", "dummy"),
    ("euchre.trump", "dummy"),
    ("euchre.led", "dummy"),
    ("euchre.upcard", "dummy"),
    ("euchre.maker", "dummy"),
    ("euchre.bids", "dummy"),
    ("euchre.alone", "dummy"),
    ("euchre.trickno", "dummy"),
    ("euchre.tricks0", "dummy"),
